GENERIC_LINES = [
    "Durable build and easy to clean.",
    "Quality checked before dispatch.",
    "Sturdy construction with a neat finish.",
    "",
    "",
]


def make_description(title: str, attrs: dict, rng: random.Random) -> str:
    """Seller-style, feature-only description (no 'use it for...' wording)."""
    spec = "; ".join(f"{k.replace('_', ' ').capitalize()}: {v}" for k, v in attrs.items())
    line = rng.choice(GENERIC_LINES)
    return f"{title}. {spec}." + (f" {line}" if line else "")


def build():
    rng = random.Random(SEED)
    rows = []
    for category, items in CATALOGUE.items():
        brands = BRANDS[category]
        for i, (ptype, sub, title, price, attrs) in enumerate(items, start=1):
            pid = f"{PREFIX[category]}-{i:03d}"
            brand = brands[i % len(brands)]
            # ~10% out of stock; otherwise 2-60 units
            stock = 0 if rng.random() < 0.10 else rng.randint(2, 60)
            rows.append({
                "product_id": pid,
                "title": title,
                "brand": brand,
                "category": category,
                "subcategory": sub,
                "product_type": ptype,
                "price_pkr": price,
                "stock_qty": stock,
                "in_stock": stock > 0,
                "attributes": attrs,
                "description": make_description(title, attrs, rng),
            })
    return rows


if __name__ == "__main__":
    import csv
    rows = build()
    (OUT_DIR / "catalogue.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False))
    with open(OUT_DIR / "catalogue.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({**r, "attributes": json.dumps(r["attributes"], ensure_ascii=False)})
    print(f"Wrote {len(rows)} products")
